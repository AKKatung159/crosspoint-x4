"""One solid icon family for the X4 home (drawn 8x supersampled, thresholded to 1-bit)."""
from PIL import Image, ImageDraw
S = 8
def _canvas(px):
    im = Image.new("L", (px * S, px * S), 0); return im, ImageDraw.Draw(im), px * S
def _finish(im, px):
    return im.resize((px, px), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0)
def library(px):   # three solid book spines, the middle one leaning
    im, d, n = _canvas(px); u = n / 48
    d.rectangle([6*u, 10*u, 15*u, 42*u], fill=255)
    d.rectangle([18*u, 6*u, 27*u, 42*u], fill=255)
    d.polygon([(31*u, 12*u), (39*u, 9*u), (46*u, 40*u), (38*u, 43*u)], fill=255)
    d.rectangle([4*u, 43*u, 46*u, 46*u], fill=255)
    return _finish(im, px)
def folder(px):
    im, d, n = _canvas(px); u = n / 48
    d.rounded_rectangle([4*u, 8*u, 22*u, 18*u], 3*u, fill=255)
    d.rounded_rectangle([4*u, 13*u, 44*u, 41*u], 4*u, fill=255)
    return _finish(im, px)
def transfer(px):  # two solid arrows: up and down
    im, d, n = _canvas(px); u = n / 48
    d.polygon([(14*u, 5*u), (25*u, 18*u), (18*u, 18*u), (18*u, 42*u), (10*u, 42*u), (10*u, 18*u), (3*u, 18*u)], fill=255)
    d.polygon([(34*u, 43*u), (45*u, 30*u), (38*u, 30*u), (38*u, 6*u), (30*u, 6*u), (30*u, 30*u), (23*u, 30*u)], fill=255)
    return _finish(im, px)
def settings(px):  # solid gear with a punched hub
    import math
    im, d, n = _canvas(px); u = n / 48; c = 24*u
    pts = []
    for i in range(16):
        a = i * math.pi / 8 + math.pi / 16
        r = 21*u if i % 2 == 0 else 15*u
        for da in (-0.17, 0.17):
            pts.append((c + r * math.cos(a + da), c + r * math.sin(a + da)))
    d.polygon(pts, fill=255); d.ellipse([c-17*u, c-17*u, c+17*u, c+17*u], fill=255)
    d.ellipse([c-7*u, c-7*u, c+7*u, c+7*u], fill=0)
    return _finish(im, px)
def resume(px):    # solid open book with a bookmark ribbon: "back to my book"
    im, d, n = _canvas(px); u = n / 48
    d.polygon([(3*u, 11*u), (22*u, 8*u), (22*u, 41*u), (3*u, 44*u)], fill=255)
    d.polygon([(26*u, 8*u), (45*u, 11*u), (45*u, 44*u), (26*u, 41*u)], fill=255)
    d.polygon([(31*u, 6*u), (39*u, 6*u), (39*u, 24*u), (35*u, 20*u), (31*u, 24*u)], fill=0)
    d.polygon([(32*u, 4*u), (38*u, 4*u), (38*u, 21*u), (35*u, 18*u), (32*u, 21*u)], fill=255)
    return _finish(im, px)
def select(px):    # solid disc
    im, d, n = _canvas(px); u = n / 48
    d.ellipse([10*u, 10*u, 38*u, 38*u], fill=255); return _finish(im, px)
def prev(px):
    im, d, n = _canvas(px); u = n / 48
    d.polygon([(34*u, 8*u), (34*u, 40*u), (10*u, 24*u)], fill=255); return _finish(im, px)
def nxt(px):
    im, d, n = _canvas(px); u = n / 48
    d.polygon([(14*u, 8*u), (14*u, 40*u), (38*u, 24*u)], fill=255); return _finish(im, px)
ICONS = {"library": library, "folder": folder, "transfer": transfer, "settings": settings,
         "resume": resume, "select": select, "prev": prev, "next": nxt}
def stamp(canvas, mask, x, y, ink=0):
    """Paint the icon mask (white = shape) onto canvas in `ink`."""
    canvas.paste(ink, (x, y), mask)



def pack(mask):
    """1bpp, MSB first, 0 = ink, rotated 90 deg CCW: the layout GfxRenderer::drawIcon reads
    (same as scripts/convert_icon.py)."""
    img = Image.eval(mask, lambda v: 255 - v).rotate(90, expand=True)   # black ink on white
    w, h = img.size
    px = img.load()
    out = []
    for y in range(h):
        for x0 in range(0, w, 8):
            byte = 0
            for b in range(8):
                if x0 + b < w and px[x0 + b, y] >= 128:
                    byte |= 1 << (7 - b)
            out.append(byte)
    return out


if __name__ == "__main__":
    # Regenerate src/components/icons/personal/homeIcons.h (44 px menu icons, 28 px hint icons).
    import os
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    lines = ["#pragma once", "#include <cstdint>", "",
             "// Generated by scripts/personal/home_icons.py -- do not edit. One solid icon family for the",
             "// personal home themes; 1bpp, MSB first, 0 = ink, rotated for GfxRenderer::drawIcon.", ""]
    for name, fn in ICONS.items():
        for size in (44, 28):
            data = pack(fn(size))
            cname = "Home" + name[0].upper() + name[1:] + str(size)
            lines.append(f"// {size}x{size}")
            lines.append(f"static const uint8_t {cname}[] = {{")
            for k in range(0, len(data), 16):
                lines.append("    " + ", ".join(f"0x{v:02X}" for v in data[k:k + 16]) + ",")
            lines.append("};")
    path = os.path.join(repo, "src", "components", "icons", "personal", "homeIcons.h")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", path)
